// ============================================================
// build-data-previews.mjs — reads the actual teaching CSVs and
// writes assets/js/data/dataset-previews.js (first 8 rows each).
// Previews are generated, never hand-written (docs/05 §4.8 spirit).
// Run: node tools/build-data-previews.mjs
// ============================================================
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parseCsv } from "./lib/extract-code.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const SPECS = [
  { id: "pika-physiology", file: "pika_physiology.csv", rows: 8 },
  { id: "pika-repeated", file: "pika_repeated.csv", rows: 8 },
  { id: "pika-survival", file: "pika_survival.csv", rows: 8 },
  { id: "pika-rnaseq-counts", file: "pika_rnaseq_counts.csv", rows: 4 },
  { id: "pika-rnaseq-metadata-raw", file: "pika_rnaseq_metadata_raw.csv", rows: 8 },
  { id: "pika-rnaseq-metadata-clean", file: "pika_rnaseq_metadata_clean.csv", rows: 8 },
  { id: "pika-annotation", file: "pika_annotation.csv", rows: 4 },
  { id: "plate-reader-raw", file: "plate_reader_raw.csv", rows: 6, skip: 3 }
];

const previews = {};
for (const s of SPECS) {
  const p = join(root, "assets", "data", s.file);
  if (!existsSync(p)) { console.warn("[warn] missing", s.file); continue; }
  let rows = parseCsv(readFileSync(p, "utf8"));
  if (s.skip) rows = rows.slice(s.skip);
  const header = rows[0];
  previews[s.id] = rows.slice(1, 1 + s.rows).map((r) => {
    const o = {};
    header.forEach((h, i) => {
      const v = r[i] === undefined ? "" : r[i];
      o[h] = v === "" ? "NA" : v;
    });
    return o;
  });
}

const js = `/* GENERATED by tools/build-data-previews.mjs — do not edit.\n` +
  ` * Rebuild: node tools/build-data-previews.mjs */\n` +
  `window.BIOR_DATASET_PREVIEWS = ${JSON.stringify(previews)};\n`;
writeFileSync(join(root, "assets", "js", "data", "dataset-previews.js"), js, "utf8");
console.log(`build-data-previews: ${Object.keys(previews).length} previews written`);
