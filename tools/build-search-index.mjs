// ============================================================
// build-search-index.mjs — executes data files in a sandboxed vm,
// collects site content and writes assets/js/data/search-index.js
// (+ .meta.json with source hashes). Docs: docs/05 §8.
// Run: node tools/build-search-index.mjs
// ============================================================
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import { createHash } from "node:crypto";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "assets", "js", "data");

const window_ = {};
const ctx = vm.createContext({ window: window_ });
for (const f of readdirSync(dataDir).sort()) {
  if (!f.endsWith(".js") || f === "search-index.js") continue;
  vm.runInContext(readFileSync(join(dataDir, f), "utf8"), ctx, { filename: f });
}

const T = window_.COURSE_TOC || [];
const SP = window_.BIOR_SPECIALS || [];
const CH = window_.BIOR_CHEATSHEETS || [];
const GL = window_.BIOR_GLOSSARY || [];
const DS = window_.BIOR_DATASETS || [];
const TRI = (window_.BIOR_TRIAGE && window_.BIOR_TRIAGE.errors) || [];
const CL = (window_.BIOR_CLINIC && window_.BIOR_CLINIC.cases) || [];
const BV = (window_.BIOR_BIOVIZ && window_.BIOR_BIOVIZ.recipes) || [];
const BI = (window_.BIOR_BIOINFO && window_.BIOR_BIOINFO.workflows) || [];

const records = [];
const push = (type, id, title, text, href, keywords) =>
  records.push({ type, id, title, text: String(text || "").slice(0, 240), href, keywords: keywords || [] });

for (const c of T) {
  push("chapter", c.id, c.title, `${c.question} ${c.summary} ${c.short}`, c.file,
    [...(c.keywords || []), c.id, `第${Number(c.id.slice(2))}章`]);
  for (const d of c.deliverable || []) {
    push("chapter", c.id + ":" + d, d, `${c.title} 的交付物`, c.file, [d, c.id]);
  }
}
for (const s of SP) push("special", s.id, s.title, s.desc, s.file, [s.id, s.title]);
for (const s of CH) push("cheatsheet", s.id, s.title,
  `${s.desc || ""} ${(s.rows || []).flat().join(" ")} ${(s.notes || []).join(" ")}`,
  `cheatsheets.html#${s.id}`, [s.category, ...(s.keywords || [])]);
for (const g of GL) push("term", g.id, g.term, `${g.en} ${g.def}`, `glossary.html#${g.id}`, [g.en, g.term]);
for (const d of DS) push("dataset", d.id, d.title,
  `${d.research_question} ${(d.variables || []).map((v) => v.name + " " + v.desc).join(" ")}`,
  `datasets.html#${d.id}`, [d.id, ...(d.chapters || [])]);
for (const e of TRI) push("special", e.id, e.message, `${e.cause || ""} ${(e.fix || []).join(" ")}`,
  `triage.html#${e.id}`, [e.category]);
for (const c of CL) push("special", c.id, c.title, `${c.symptom} ${c.diagnosis}`,
  `clinic.html#${c.id}`, [c.category]);
for (const r of BV) push("special", r.id, r.title, `${r.question} ${r.data_shape}`,
  `bioviz.html#${r.id}`, [r.category]);
for (const w of BI) push("special", w.id, w.title, w.lede, `bioinfo.html#${w.id}`, [w.id]);

const js = `/* GENERATED by tools/build-search-index.mjs — do not edit.\n` +
  ` * Rebuild: node tools/build-search-index.mjs */\n` +
  `window.BIOR_SEARCH_INDEX = ${JSON.stringify(records)};\n`;
writeFileSync(join(dataDir, "search-index.js"), js, "utf8");

const hash = (p) => createHash("sha256").update(readFileSync(p)).digest("hex").slice(0, 16);
const meta = {
  generated: new Date().toISOString(),
  records: records.length,
  sources: readdirSync(dataDir).filter((f) => f.endsWith(".js") && f !== "search-index.js" && f !== "search-index.meta.json")
    .map((f) => ({ file: f, hash: hash(join(dataDir, f)) }))
};
writeFileSync(join(dataDir, "search-index.meta.json"), JSON.stringify(meta, null, 2), "utf8");
console.log(`build-search-index: ${records.length} records (chapter ${T.length}, special ${SP.length}, cheat ${CH.length}, term ${GL.length}, dataset ${DS.length})`);
