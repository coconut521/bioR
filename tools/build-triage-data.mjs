/* ============================================================
 * build-triage-data.mjs — tools/errors/errors.json →
 * assets/js/data/triage-data.js (window.BIOR_TRIAGE).
 * Keeps the triage page and its search index on the same real,
 * collected error records; never hand-write error text.
 * Run: node tools/build-triage-data.mjs
 * ============================================================ */
import fs from "node:fs";

const root = process.cwd();
const errors = JSON.parse(fs.readFileSync(`${root}/tools/errors/errors.json`, "utf8"));
const payload = {
  generated: new Date().toISOString().slice(0, 10),
  r_version: errors[0] ? errors[0].r_version : "",
  errors: errors.map((e) => ({
    id: e.id,
    category: e.category,
    kind: e.kind,
    message: e.message,
    minimal: e.minimal,
    r_version: e.r_version
  }))
};
const out = `/* GENERATED by tools/build-triage-data.mjs — do not edit.
 * Source: tools/errors/errors.json (real R ${payload.r_version} runs).
 */
window.BIOR_TRIAGE = ${JSON.stringify(payload, null, 2)};
`;
fs.writeFileSync(`${root}/assets/js/data/triage-data.js`, out, "utf8");
console.log(`build-triage-data: ${payload.errors.length} errors written`);
